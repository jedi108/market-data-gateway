func TestRealizedVolGolden(t *testing.T) {
	if got, want := RealizedVol(fixtureClose), 0.013281858448254155; math.Abs(got-want) > 1e-12 {
		t.Fatalf("realized vol = %.15f, want %.15f", got, want)
	}
}

func TestShortInputsStayNaN(t *testing.T) {
	short := fixtureClose[:3]
	for name, series := range map[string][]float64{
		"ema": EMA(short, goldenPeriod),
		"atr": ATR(fixtureHigh[:3], fixtureLow[:3], short, goldenPeriod),
		"adx": ADX(fixtureHigh[:3], fixtureLow[:3], short, goldenPeriod),
	} {
		for i, v := range series {
			if !math.IsNaN(v) {
				t.Errorf("%s[%d] = %v, want NaN for too-short input", name, i, v)
			}
		}
	}
	if !math.IsNaN(RealizedVol(short[:2])) {
		t.Error("realized vol of two closes must be NaN")
	}
}
