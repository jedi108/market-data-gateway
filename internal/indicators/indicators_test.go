const goldenPeriod = 5

func assertGolden(t *testing.T, name string, got []float64, want map[int]float64) {
	t.Helper()
	if len(got) != len(fixtureClose) {
		t.Fatalf("%s: len %d, want %d", name, len(got), len(fixtureClose))
	}
	for index, expected := range want {
		if math.IsNaN(expected) {
			if !math.IsNaN(got[index]) {
				t.Errorf("%s[%d] = %v, want NaN (warm-up)", name, index, got[index])
			}
			continue
		}
		if math.Abs(got[index]-expected) > 1e-9 {
			t.Errorf("%s[%d] = %.15f, want %.15f", name, index, got[index], expected)
		}
	}
}

func TestEMAGolden(t *testing.T) {
	assertGolden(t, "ema", EMA(fixtureClose, goldenPeriod), map[int]float64{
		3: math.NaN(), 4: 104.34017247479653, 5: 106.19835159922401, 9: 110.99447936973041, 20: 101.14512524368035, 39: 119.30620290750323,
	})
}

